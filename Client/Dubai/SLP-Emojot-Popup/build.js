// Builds vercel/popup.js from emojot-register-popup.html (the single source of truth).
// Usage: node build.js   then deploy:   cd vercel && npx vercel deploy --prod
const fs = require('fs');
const path = require('path');

const src = fs.readFileSync(path.join(__dirname, 'emojot-register-popup.html'), 'utf8');
const css = (src.match(/<style>([\s\S]*?)<\/style>/) || [])[1];
const js = (src.match(/<script>([\s\S]*?)<\/script>/) || [])[1];
const fontHref = (src.match(/<link href="(https:\/\/fonts\.googleapis\.com\/css2[^"]+)"/) || [])[1];
if (!css || !js || !fontHref) throw new Error('Could not find <style>, <script> or the font link in emojot-register-popup.html');

const out =
`/* SLP – Emojot register + booking popup. Generated by build.js from emojot-register-popup.html; do not edit. */
(function () {
  if (window.__ejrLoaded) return;
  var head = document.head || document.documentElement;
  var font = document.createElement('link');
  font.rel = 'stylesheet';
  font.href = ${JSON.stringify(fontHref)};
  head.appendChild(font);
  var style = document.createElement('style');
  style.textContent = ${JSON.stringify(css.trim())};
  head.appendChild(style);
})();
${js.trim()}
`;

fs.mkdirSync(path.join(__dirname, 'vercel'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'vercel', 'popup.js'), out);
console.log('Wrote vercel/popup.js (' + Math.round(out.length / 1024) + ' KB)');

// preview.html = the Vercel test page with the popup pasted inline, so it opens by double-click
const page = fs.readFileSync(path.join(__dirname, 'vercel', 'index.html'), 'utf8');
const tag = '<script src="/popup.js" defer></script>';
if (page.indexOf(tag) < 0) throw new Error('vercel/index.html no longer loads ' + tag);
const preview = page
  .replace('<title>SLP – Emojot popup</title>', '<title>SLP – Emojot popup preview</title>')
  .replace(tag, () => '<!-- ===== popup snippet (copied from emojot-register-popup.html) ===== -->\n' + src.trim());
fs.writeFileSync(path.join(__dirname, 'preview.html'), preview);
console.log('Wrote preview.html');
